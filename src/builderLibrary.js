// Sensible starting choices for a new cake bakery (it can change all of them).
export const STARTER = {
  shapes: ['round', 'heart', 'tall'],
  sizes: ['6', '8', '10'],
  flavours: ['vanilla', 'chocolate', 'red-velvet', 'marble', 'lemon', 'carrot', 'strawberry', 'oreo'],
  fillings: ['bakers-choice', 'vanilla-cream', 'chocolate-ganache', 'strawberry-jam', 'cream-cheese', 'lemon-curd'],
  frostings: ['bakers-choice', 'buttercream', 'cream-cheese', 'ganache', 'whipped-cream'],
  toppings: ['sprinkles', 'shavings', 'berries', 'drizzle'],
}

export const pick = (kind, ids) => ids.map((id) => LIBRARY[kind].find((item) => item.id === id)).filter(Boolean).map((item) => ({ ...item }))

export function starterCake() {
  return {
    kind: 'cake',
    noun: 'cake',
    maxLayers: 4,
    layerPrice: DEFAULT_LAYER_PRICE,
    ...Object.fromEntries(Object.entries(STARTER).map(([kind, ids]) => [kind, pick(kind, ids)])),
  }
}

function asOptions(kind, value, fallbackIds) {
  if (!Array.isArray(value) || !value.length) return pick(kind, fallbackIds)
  return value
    .map((item) => (typeof item === 'string' ? LIBRARY[kind].find((entry) => entry.id === item) || { id: item, label: item, price: 0 } : item))
    .map((item) => (kind === 'sizes' && item.serves == null ? { ...item, serves: LIBRARY.sizes.find((entry) => entry.id === item.id)?.serves || '' } : item))
    .filter((item) => item && item.label)
}

// Options a customer sees for a cake builder (handles older saved menus too).
export function cakeOptions(builder = {}) {
  return {
    shapes: asOptions('shapes', builder.shapes, ['round', 'heart']),
    sizes: asOptions('sizes', builder.sizes, STARTER.sizes),
    flavours: asOptions('flavours', builder.flavours, STARTER.flavours.slice(0, 4)),
    fillings: asOptions('fillings', builder.fillings, STARTER.fillings),
    frostings: asOptions('frostings', builder.frostings, STARTER.frostings),
    toppings: Array.isArray(builder.toppings) ? asOptions('toppings', builder.toppings, []) : pick('toppings', STARTER.toppings),
    layerPrice: Number.isFinite(Number(builder.layerPrice)) && builder.layerPrice !== '' && builder.layerPrice != null ? Number(builder.layerPrice) : DEFAULT_LAYER_PRICE,
    maxLayers: Number(builder.maxLayers) || 4,
  }
}
